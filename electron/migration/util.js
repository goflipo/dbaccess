// Connection helpers, option normalisation and script rendering shared by the migration modules.
// Never requires 'electron' so tests can run it under plain ELECTRON_RUN_AS_NODE.

const { family, pg, my } = require('./sql');

const DEFAULTS = {
  tables: null, includeSchema: true, includeData: false, dataMode: 'append', allowDrops: false,
  dropExtraTables: false, dropExtraColumns: false, alterTypes: true, createIndexes: true, createConstraints: true,
  createViews: true, syncSequences: true, batchSize: 1000, onError: 'stop', dryRun: false, autoIncludeDeps: true,
};

function normalizeOptions(o) {
  const opts = Object.assign({}, DEFAULTS, o || {});
  if (!['append', 'insert-missing', 'upsert', 'truncate-copy'].includes(opts.dataMode)) opts.dataMode = 'append';
  if (!['stop', 'continue'].includes(opts.onError)) opts.onError = 'stop';
  opts.batchSize = Math.max(1, Math.min(50000, parseInt(opts.batchSize, 10) || 1000));
  if (opts.tables && !Array.isArray(opts.tables)) opts.tables = null;
  if (!opts.allowDrops) { opts.dropExtraTables = false; opts.dropExtraColumns = false; }
  return opts;
}

function getConn(dbManager, id) {
  const c = typeof dbManager.getConnection === 'function' ? dbManager.getConnection(id) : dbManager.connections.get(id);
  if (!c) throw new Error('Connection not found: ' + id);
  return c;
}

/** Run fn with a dedicated client (pg PoolClient / mysql2 PoolConnection) and always release it. */
async function withClient(dbManager, id, fn) {
  const conn = getConn(dbManager, id);
  const fam = family(conn.type);
  if (fam === 'postgres') {
    const c = await conn.client.connect();
    try { return await fn(c, conn); } finally { c.release(); }
  }
  if (fam === 'mysql') {
    const c = await conn.client.getConnection();
    try { return await fn(c, conn); } finally { c.release(); }
  }
  throw new Error('Unsupported engine: ' + conn.type);
}

const sameHost = (a, b) => String(a || '').toLowerCase().replace(/^localhost$|^::1$/, '127.0.0.1') === String(b || '').toLowerCase().replace(/^localhost$|^::1$/, '127.0.0.1');
function sameDatabase(a, b, aId, bId) {
  if (aId === bId) return true;
  const x = a.config || {}, y = b.config || {};
  const dp = (t) => (family(t) === 'mysql' ? 3306 : 5432);
  return sameHost(x.host, y.host) && (parseInt(x.port, 10) || dp(a.type)) === (parseInt(y.port, 10) || dp(b.type)) &&
    String(a.activeDb || x.database) === String(b.activeDb || y.database) && family(a.type) === family(b.type);
}

const norm = (s) => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
const MAX_ROWS_FOR_COMMENTS = 0;

function stepFactory() {
  let n = 0;
  const steps = [];
  const PRE = new Set(['types', 'sequences', 'tables', 'columns']);
  const RANK = { types: 0, sequences: 1, tables: 2, columns: 3, constraints: 4, indexes: 7, views: 8, 'sequence-sync': 9, drops: 10 };
  function add(phase, kind, object, sql, description, extra = {}) {
    const s = Object.assign({
      id: 's' + (++n), phase, kind, object, sql, destructive: false, description,
      preData: PRE.has(phase) || (phase === 'constraints' && !!extra.preData),
    }, extra);
    s._rank = extra.rank != null ? extra.rank : phase === 'constraints' ? (s.preData ? 4 : 6) : RANK[phase];
    delete s.rank;
    s._ord = extra.first ? n - 100000 * (3 - extra.first) : n;
    delete s.first;
    steps.push(s);
    return s;
  }
  function finish() {
    steps.sort((a, b) => a._rank - b._rank || a._ord - b._ord);
    steps.forEach((s, i) => { s.id = 's' + (i + 1); delete s._rank; delete s._ord; });
    return steps;
  }
  return { add, finish, steps };
}

const GUARDED = new Set(['create-type', 'add-pk', 'add-unique', 'add-check', 'add-fk', 'add-exclusion']);

/** Render the human-readable SQL script for the schema steps (data copy shown as comments). */
function renderScript(plan, ctx) {
  const L = [];
  const isPg = plan.engine === 'postgres';
  const one = (s) => String(s == null ? '' : s).replace(/[\r\n]+/g, ' ');
  L.push('-- Migration script generated by DB Access');
  L.push(`-- Engine: ${plan.engine}   Source: ${one(ctx.srcLabel)}   Target: ${one(ctx.tgtLabel)}`);
  L.push(`-- Generated at: ${new Date().toISOString()} from the live catalogs (schema only; row data is copied by the app)`);
  if (!isPg) L.push('-- NOTE: MySQL DDL is not transactional (implicit commit); steps are written to be re-runnable where possible.');
  L.push('');
  let phase = null, open = false, dataShown = false;
  const close = () => { if (open) { L.push('COMMIT;'); L.push(''); open = false; } };
  const dataBlock = () => {
    if (dataShown) return; dataShown = true;
    if (!plan.dataPlan || !plan.dataPlan.length) return;
    close();
    L.push('-- === PHASE: data (performed by the application, not part of this script) ===');
    for (const d of plan.dataPlan) L.push(`-- DATA: copy ${one(d.table)} (${d.sourceRows == null ? '?' : d.sourceRows} rows) [${d.mode}]`);
    L.push('');
  };
  let seenPost = false;
  for (const s of plan.steps) {
    if (!s.preData && !seenPost) { seenPost = true; dataBlock(); phase = null; }
    if (s.phase !== phase) {
      close(); phase = s.phase;
      L.push(`-- === PHASE: ${phase} ===`);
    }
    if (isPg && !s.autocommit && !open) { L.push('BEGIN;'); open = true; }
    if (isPg && s.autocommit && open) { L.push('COMMIT;'); open = false; }
    L.push(`-- ${one(s.description)}${s.destructive ? '  -- DESTRUCTIVE' : ''}`);
    const sql = String(s.sql).replace(/;\s*$/, '');
    if (isPg && GUARDED.has(s.kind)) L.push(`DO $mig$ BEGIN ${sql}; EXCEPTION WHEN duplicate_object OR duplicate_table OR invalid_table_definition THEN NULL; END $mig$;`);
    else L.push(sql + ';');
    if (s.commentedFollowUp) L.push('-- ' + one(s.commentedFollowUp));
  }
  if (!seenPost) dataBlock();
  close();
  for (const sk of plan.skippedDrops || []) L.push(`-- SKIPPED (allowDrops=false): ${one(sk)}`);
  return L.join('\n') + '\n';
}

module.exports = { normalizeOptions, getConn, withClient, sameDatabase, norm, stepFactory, renderScript, pg, my, MAX_ROWS_FOR_COMMENTS };
